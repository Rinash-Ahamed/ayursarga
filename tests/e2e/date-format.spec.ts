import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { bundleDialogHarness } from "../helpers/bundleDialogHarness";
const bundle = bundleDialogHarness("tests/fixtures/dateInputHarness.tsx");
test.use({ locale: "en-US", timezoneId: "America/Los_Angeles" });
test("DD/MM/YYYY date controls preserve ISO payloads across typing, native picking and resets", async ({ page }) => {
  await page.setContent('<html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="fixture-root"></div></body></html>');
  for (const file of ["node_modules/tailwindcss/lib/css/preflight.css", "app/globals.css", "app/portal.css"]) await page.addStyleTag({ content: readFileSync(file, "utf8") });
  await page.addScriptTag({ content: bundle });
  const care = page.getByRole("textbox", { name: "Care date", exact: true });
  await expect(care).toHaveValue("05/11/2026");
  await expect(page.getByRole("textbox", { name: "Signing date" })).toHaveValue("11/05/2026");
  await page.locator('[name="careDate"]').evaluate((input: HTMLInputElement) => { input.showPicker = () => { input.dataset.pickerOpened = "true"; }; });
  await page.locator(".date-input-control").first().getByRole("button", { name: "Open calendar", exact: true }).click();
  await expect(page.locator('[name="careDate"]')).toHaveAttribute("data-picker-opened", "true");
  await care.fill("11/05/2026");
  await page.getByRole("button", { name: "Save dates", exact: true }).click();
  await expect(page.locator("output")).toContainText('"careDate":"2026-05-11"');
  await care.fill("");
  await care.pressSequentially("05112026");
  await expect(care).toHaveValue("05/11/2026");
  await expect(page.locator('[name="careDate"]')).toHaveValue("2026-11-05");
  await care.fill("31/04/2026");
  await care.blur();
  await expect(care).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByRole("alert")).toContainText("DD/MM/YYYY");
  await expect(page.locator('[name="careDate"]')).toHaveValue("");
  await page.locator('[name="careDate"]').fill("2026-11-06");
  await expect(care).toHaveValue("06/11/2026");
  await page.getByRole("button", { name: "Update expiry", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Expiry date" })).toHaveValue("05/11/2030");
  await page.getByRole("button", { name: "Reset dates", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Expiry date" })).toHaveValue("05/11/2029");
  await page.getByRole("textbox", { name: "Signing date" }).fill("");
  await expect(page.getByRole("textbox", { name: "Signing date" })).toHaveValue("");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
